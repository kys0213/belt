    fn record_history(&mut self, item: &QueueItem, status: &str, error: Option<&str>) {
        let attempt = self
            .history
            .iter()
            .filter(|h| h.state == item.state)
            .count() as u32
            + 1;
        self.history.push(HistoryEntry {
            source_id: item.source_id.clone(),
            work_id: item.work_id.clone(),
            state: item.state.clone(),
            status: status
                .parse()
                .unwrap_or(belt_core::context::HistoryStatus::Failed),
            attempt,
            summary: None,
            error: error.map(|s| s.to_string()),
            created_at: chrono::Utc::now().to_rfc3339(),
        });
    }

    fn record_history_event(&mut self, item: &QueueItem, status: &str, error: Option<String>) {
        let attempt = self
            .history_events
            .iter()
            .filter(|h| h.source_id == item.source_id && h.state == item.state)
            .count() as u32
            + 1;
        let event = HistoryEvent {
            work_id: item.work_id.clone(),
            source_id: item.source_id.clone(),
            state: item.state.clone(),
            status: status.to_string(),
            attempt,
            summary: None,
            error,
            created_at: Utc::now(),
        };

        // Persist to DB when available (R-018: DB is the source of truth).
        let db_event = belt_infra::db::HistoryEvent {
            work_id: event.work_id.clone(),
            source_id: event.source_id.clone(),
            state: event.state.clone(),
            status: event.status.clone(),
            attempt: event.attempt as i32,
            summary: event.summary.clone(),
            error: event.error.clone(),
            created_at: event.created_at.to_rfc3339(),
        };
        if let Err(e) = self.db.append_history(&db_event) {
            tracing::warn!(error = %e, "failed to persist history event to DB");
        }

        self.history_events.push(event);
    }

