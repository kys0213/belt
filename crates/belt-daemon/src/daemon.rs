    /// Detect stagnation from failure history and generate a lateral plan directive.
    ///
    /// Collects the stored failure messages of the item's `(source_id, state)`,
    /// runs them through a `StagnationDetector` (spinning + oscillation detection via
    /// `CompositeSimilarity`), and if a pattern is detected, selects a persona via
    /// `LateralAnalyzer` and builds a directive-based lateral plan string.
    /// `failure_count` is this failure's position in the lineage.
    ///
    /// # Errors
    /// `BeltError` when the stored history cannot be read. There is no
    /// in-memory substitute: the store is the only failure history.
    fn detect_stagnation_and_generate_plan(
        &self,
        item: &QueueItem,
        current_error: &str,
        failure_count: u32,
    ) -> Result<Option<String>, BeltError> {
        let (work_id, source_id, state) = (&item.work_id, &item.source_id, &item.state);

        // Respect stagnation.enabled configuration flag.
        if !self.config.stagnation.enabled {
            return Ok(None);
        }

        // Respect lateral.enabled configuration flag.
        if !self.config.stagnation.lateral.enabled {
            return Ok(None);
        }

        // Collect recent failure error messages for this source_id + state.
        let errors: Vec<String> = self
            .db
            .get_history(source_id)?
            .into_iter()
            .filter(|h| h.state == *state && h.status == "failed")
            .filter_map(|h| h.error)
            .collect();

        // Need at least one prior failure to detect stagnation.
        if errors.is_empty() {
            return Ok(None);
        }

        // Build outputs list: prior errors + current error.
        let mut outputs: Vec<&str> = errors.iter().map(|s| s.as_str()).collect();
        outputs.push(current_error);

        // Similarity threshold and repeat counts match the documented defaults on
        // SpinningDetector::new / OscillationDetector::new in belt_core::stagnation::pattern
        // (threshold=0.9, count=2) -- kept as code constants, not exposed via yaml.
        const SIMILARITY_THRESHOLD: f64 = 0.9;
        const SPINNING_MIN_CONSECUTIVE: usize = 2;
        const OSCILLATION_MIN_CYCLES: usize = 2;

        // Run stagnation detection with the CompositeSimilarity default preset
        // (ExactHash 0.5 + TokenFingerprint 0.3 + NcdJudge 0.2, see
        // belt_core::stagnation::similarity::CompositeSimilarity::default), checking for
        // both oscillation (A-B-A-B) and spinning (consecutive-pair) patterns.
        //
        // OscillationDetector is registered before SpinningDetector: StagnationDetector::detect
        // picks the highest-confidence match and, on a tie, `Iterator::max_by` returns the last
        // one seen. A run of identical outputs trivially satisfies the A-B-A-B check too (A~A),
        // tying both detectors' confidence -- registering Spinning last keeps a true repeat
        // labeled Spinning, its more specific pattern, while a genuine A/B alternation (where
        // Spinning never fires) is still labeled Oscillation.
        let detector = StagnationDetector::new(vec![
            Box::new(OscillationDetector::new(
                Box::new(CompositeSimilarity::default()),
                SIMILARITY_THRESHOLD,
                OSCILLATION_MIN_CYCLES,
            )),
            Box::new(SpinningDetector::new(
                Box::new(CompositeSimilarity::default()),
                SIMILARITY_THRESHOLD,
                SPINNING_MIN_CONSECUTIVE,
            )),
        ]);

        let Some(detection) = detector.detect(&outputs) else {
            return Ok(None);
        };

        // Collect previously attempted personas from lateral_plan history in queue.
        let attempted: Vec<Persona> = self
            .queue
            .iter()
            .filter(|q| q.source_id == *source_id && q.state == *state)
            .filter_map(|q| q.lateral_plan.as_deref())
            .filter_map(|plan| {
                // Extract persona name from the plan text.
                plan.lines()
                    .find(|l| l.contains("Persona:"))
                    .and_then(|l| l.split("Persona:").nth(1))
                    .and_then(|s| match s.trim().to_lowercase().as_str() {
                        "hacker" => Some(Persona::Hacker),
                        "architect" => Some(Persona::Architect),
                        "researcher" => Some(Persona::Researcher),
                        "simplifier" => Some(Persona::Simplifier),
                        "contrarian" => Some(Persona::Contrarian),
                        _ => None,
                    })
            })
            .collect();

        let analyzer = LateralAnalyzer::new();
        let Some(persona) = analyzer.select_persona(detection.pattern, &attempted) else {
            return Ok(None);
        };

        let plan = format!(
            "\n\n## Lateral Plan\n\
             Stagnation Analysis (attempt {failure_count})\n\
             Pattern: {pattern} | Persona: {persona}\n\n\
             {directive}\n\n\
             Warning: Previous approaches produced similar failures. \
             You MUST try a fundamentally different approach.",
            pattern = detection.pattern,
            persona = persona,
            directive = persona.directive(),
        );

        // Record stagnation detection event in transition_events.
        let detail = serde_json::json!({
            "pattern_type": detection.pattern.to_string(),
            "confidence": detection.confidence,
            "reason": detection.reason,
            "recommended_persona": persona.to_string(),
            "failure_count": failure_count,
        });
        Self::record_stagnation_event(&self.db, work_id, source_id, &detail.to_string());

        tracing::info!(
            source_id = %source_id,
            state = %state,
            pattern = %detection.pattern,
            persona = %persona,
            confidence = detection.confidence,
            "stagnation detected, generated lateral plan"
        );

        Ok(Some(plan))
    }

